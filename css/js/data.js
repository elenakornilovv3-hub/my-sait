/* Плейсхолдеры-обложки (data-URI, работают офлайн). Замените на реальные картинки. */
function coverOf(game) {
  const palettes = [
    ['#1b3b6f', '#4fc3f7'], ['#2a1042', '#7c5cff'], ['#102a24', '#23d5ab'],
    ['#3a1c2b', '#ff5c7a'], ['#1c2a3a', '#5c8cff'], ['#2b2b12', '#c9d523'],
    ['#12303a', '#3ad5c5'], ['#301a1a', '#ff8a4c']
  ];
  const [a, b] = palettes[(game.id - 1) % palettes.length];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="500">
    <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="#050a10"/>
    </linearGradient></defs>
    <rect width="800" height="500" fill="url(#g)"/>
    <circle cx="640" cy="110" r="150" fill="${b}" opacity="0.18"/>
    <circle cx="170" cy="400" r="190" fill="${b}" opacity="0.10"/>
    <text x="50" y="380" font-family="Segoe UI, sans-serif" font-size="54" font-weight="800"
      fill="#ffffff" opacity="0.92">${game.title}</text>
    <text x="50" y="425" font-family="Segoe UI, sans-serif" font-size="24"
      fill="${b}" opacity="0.9">${game.genre.toUpperCase()}</text>
  </svg>`;
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

